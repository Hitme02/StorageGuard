"""Export the presentation's pre-recorded data into demo/web/public/data/.

    venv/bin/python demo/export.py

* ``results.json``: every chart's numbers, parsed from results/REPORT.md and results/aggregates.csv
  (both generated by ``sg report``; nothing here is typed by hand).
* fallback runs for a set of showcase tickets, so the app still works when the backend is not running:
  live scripted runs, recorded LLM episodes, real-file sandbox runs, maps and the threshold sweep grid.
* ``zfs/``: one ticket under every model and method as replayed on OpenZFS (see ``export_zfs.py``).
"""

from __future__ import annotations

import csv
import json
import re
import shutil
import sys
import time
from collections import defaultdict
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import engine  # noqa: E402

OUT = HERE / "web" / "public" / "data"
RES = engine.results_root()
MAIN_MODELS = ("llama3.1-8b", "ministral-3-8b", "qwen2.5-7b")
MAIN_CONFIGS = ("noguard", "prompt_only", "rbac", "llm_judge", "storageguard")
HOOK_TASK = "task-854ce268"  # results/case_studies/case_1.md
TAU_ALLOW = (0.05, 0.1, 0.15, 0.2, 0.25, 0.35, 0.5)
TAU_BLOCK = (0.4, 0.55, 0.7, 0.85, 0.95)


def write(rel: str, obj: Any) -> None:
    p = OUT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(obj, separators=(",", ":"), default=str))


# --------------------------------------------------------------------------- #
# REPORT.md -> tables
# --------------------------------------------------------------------------- #


def report_sections() -> dict[str, list[str]]:
    secs: dict[str, list[str]] = {}
    cur = "_"
    for line in (RES / "REPORT.md").read_text().splitlines():
        if line.startswith("## "):
            cur = line[3:].strip()
            secs[cur] = []
        else:
            secs.setdefault(cur, []).append(line)
    return secs


def tables(lines: list[str]) -> list[list[dict[str, str]]]:
    out, cur = [], []
    for line in [*lines, ""]:
        if line.startswith("|"):
            cur.append([c.strip() for c in line.strip().strip("|").split("|")])
        elif cur:
            head, rows = cur[0], [r for r in cur[2:]]
            out.append([dict(zip(head, r, strict=False)) for r in rows])
            cur = []
    return out


def pct(s: str) -> float | None:
    m = re.match(r"\s*([-+]?\d+(?:\.\d+)?)%?", s or "")
    return float(m.group(1)) if m else None


def ci(s: str) -> list[float] | None:
    m = re.search(r"\[([-+]?\d+(?:\.\d+)?),\s*([-+]?\d+(?:\.\d+)?)\]", s or "")
    return [float(m.group(1)), float(m.group(2))] if m else None


def section(secs: dict[str, list[str]], prefix: str) -> list[str]:
    for k, v in secs.items():
        if k.startswith(prefix):
            return v
    raise KeyError(prefix)


def build_results() -> dict[str, Any]:
    secs = report_sections()
    out: dict[str, Any] = {"source": "results/REPORT.md and results/aggregates.csv (generated by sg report)"}

    # main table with confidence intervals, from aggregates.csv
    agg = []
    with open(RES / "aggregates.csv") as fh:
        for r in csv.DictReader(fh):
            agg.append({"model": r["model"], "config": r["config"],
                        **{k: float(r[k]) for k in ("unsafe", "unsafe_lo", "unsafe_hi", "success", "success_lo",
                                                     "success_hi", "n_escalations", "n_escalations_lo",
                                                     "n_escalations_hi", "steps", "tokens")}})  # fmt: skip
    out["aggregates"] = agg

    rq1 = section(secs, "RQ1")
    heat = tables(rq1)[0]
    out["heatmap"] = [{"trap": r["Type"], **{k: pct(v) for k, v in r.items() if k != "Type"}} for r in heat]
    m = re.search(r"H1 (\d+)%, H2 (\d+)%, H3 (\d+)%, H4 (\d+)%, H5 (\d+)%, H6 (\d+)%; median data at stake (\d+) GB",
                  "\n".join(rq1))  # fmt: skip
    if m:
        out["harm_types"] = {f"H{i + 1}": int(m.group(i + 1)) for i in range(6)} | {"median_gb": int(m.group(7))}

    rq2 = tables(section(secs, "RQ2"))
    out["main_table"] = [{"model": r["Model"], "config": r["Config"], "uar": pct(r["UAR"]), "uar_ci": ci(r["UAR"]),
                          "tsr": pct(r["TSR"]), "tsr_ci": ci(r["TSR"]), "esc": pct(r["Esc/task"]),
                          "stop_precision": r["Stop precision"], "fbr": pct(r["FBR (routine)"])} for r in rq2[0]]  # fmt: skip
    out["per_category"] = [{"model": r["Model"], "config": r["Config"],
                            **{k.replace(" ", "_"): pct(v) for k, v in r.items() if k not in ("Model", "Config")}}
                           for r in rq2[1]]  # fmt: skip
    out["significance"] = rq2[2]

    rq3 = tables(section(secs, "RQ3"))
    conv = lambda rows: [{"model": r["Model"], "config": r["Config"], "uar": pct(r["UAR"]), "tsr": pct(r["TSR"]),  # noqa: E731
                          "esc": pct(r["Esc/task"]), "fbr": pct(r["FBR (routine)"]), "steps": pct(r["Steps"]),
                          "tokens": pct(r["Tokens"])} for r in rows]  # fmt: skip
    out["ablations"], out["sensitivity"] = conv(rq3[0]), conv(rq3[1])

    fb = []
    for line in section(secs, "RQ4"):
        mm = re.search(r"- (.+?), (\S+): (\d+) episodes had .*?safe completion after a block ([\d.]+)%; (\d+) episodes had a rewrite, goal still met in ([\d.]+)%", line)  # noqa: E501
        if mm:
            fb.append({"config": mm.group(1), "model": mm.group(2), "stopped": int(mm.group(3)),
                       "safe_after_block": float(mm.group(4)), "rewrites": int(mm.group(5)),
                       "rewrite_goal_met": float(mm.group(6))})  # fmt: skip
    out["feedback"] = fb

    out["injection"] = [{"model": r["Model"], "config": r["Config"], "uar": pct(r["UAR"]), "tsr": pct(r["TSR"]),
                         "P1": pct(r["P1 UAR"]), "P2": pct(r["P2 UAR"]), "P3": pct(r["P3 UAR"])}
                        for r in tables(section(secs, "RQ5"))[0]]  # fmt: skip

    rq6 = "\n".join(section(secs, "RQ6"))
    mm = re.search(r"over (\d+) mutating calls .*?median ([\d.]+) ms, p95 ([\d.]+) ms, p99 ([\d.]+) ms, max ([\d.]+) ms", rq6)
    if mm:
        out["latency"] = {"calls": int(mm.group(1)), "median": float(mm.group(2)), "p95": float(mm.group(3)),
                          "p99": float(mm.group(4)), "max": float(mm.group(5))}  # fmt: skip
    out["judge_calls"] = [{"model": a, "calls": float(b)} for a, b in re.findall(r"- (\S+), B3 LLM judge .*?judge calls/task ([\d.]+)", rq6)]

    sc = tables(section(secs, "RQ7"))
    out["scale"] = [{"model": r["Model"], "size": r["Size"], "weights": r["Weights"],
                     **{f"{c}_uar": pct(r[f"{c} UAR"]) for c in ("B0", "B1", "B2", "B3", "B4")},
                     **{f"{c}_tsr": pct(r[f"{c} TSR"]) for c in ("B0", "B1", "B2", "B3", "B4")},
                     "b4_esc": pct(r["B4 esc/task"]), "b4_safe_after_block": pct(r["B4 safe after block"])}
                    for r in sc[0]]  # fmt: skip
    out["scale_category"] = [{"model": r["Model"], **{k.replace(" ", "_"): pct(v) for k, v in r.items() if k != "Model"}}
                             for r in sc[1]]  # fmt: skip

    out["policy"] = [{"plan": r["Plan"], "config": r["Config"], "uar": pct(r["UAR (trap+inj)"]), "tsr": pct(r["TSR (all)"]),
                      "fbr": pct(r["FBR (routine)"]), "esc": pct(r["Esc/task"]), "rewrites": pct(r["Rewrites/task"])}
                     for r in tables(section(secs, "Policy-level"))[0]]  # fmt: skip

    out["physical"] = [{"config": r["Configuration"], "episodes": int(r["Episodes"]), "oracle_uar": pct(r["Oracle UAR %"]),
                        "phys_harm": pct(r["Physical harm %"]), "phys_harm_ci": ci(r["Physical harm %"]),
                        "data_destroyed": pct(r["Data destroyed/rolled back %"]),
                        "datasets_destroyed": int(r["Datasets destroyed"]), "tb_destroyed": pct(r["Logical TB destroyed"]),
                        "outage": pct(r["Outage %"]), "site_drill": pct(r["Site drill %"]),
                        "ransom_drill": pct(r["Ransomware drills %"]), "files_deleted": int(r["Files deleted"])}
                       for r in tables(section(secs, "RQ8."))[0]]  # fmt: skip

    zfs = "\n".join(section(secs, "RQ8b"))
    mm = re.search(r"agreed with the twin on \*\*(\d+)\*\* \(([\d.]+)%\)", zfs)
    tr = re.search(r"trajectories: (\d+) covering (\d+) replayed episodes", zfs)
    cas = re.search(r"cascade .*? in (\d+)/(\d+) calls", zfs)
    comp = re.search(r"Of the (\d+) with a native ZFS counterpart", zfs)
    out["zfs"] = {"agreed": int(mm.group(1)) if mm else None, "agree_pct": float(mm.group(2)) if mm else None,
                  "trajectories": int(tr.group(1)) if tr else None, "episodes": int(tr.group(2)) if tr else None,
                  "cascade_match": [int(cas.group(1)), int(cas.group(2))] if cas else None,
                  "comparable": int(comp.group(1)) if comp else None}  # fmt: skip
    rs = tables(zfs.splitlines())
    if rs:
        out["restore_sensitivity"] = [{"config": r["Configuration"], "twin": pct(r["harm %, twin"]),
                                       "rollback": pct(r["harm %, rollback"]), "rollback_r": pct(r["harm %, rollback -r"]),
                                       "beyond_reference": pct(r["harm %, rollback -r, beyond the reference plan"])}
                                      for r in rs[-1]]  # fmt: skip

    ph = "\n".join(section(secs, "Post hoc"))
    mm = re.search(r"physically harmful episodes, B4 (\d+) of (\d+), B4\+PIT (\d+) of (\d+)", ph)
    out["pit"] = {"b4": int(mm.group(1)), "of": int(mm.group(2)), "pit": int(mm.group(3))} if mm else None

    out["benchmark"] = [{"category": r["Category"], "type": r["Type"], "total": int(r["Total"]), "dev": int(r["Dev"]),
                         "test": int(r["Test"])} for r in tables(section(secs, "Benchmark"))[0]]  # fmt: skip
    return out


