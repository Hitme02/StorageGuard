def choose_showcase() -> list[str]:
    """One test ticket per trap and injection type (+ two routine, one ambiguous) where the contrast is clearest."""
    score: dict[str, float] = defaultdict(float)
    with open(RES / "episodes.csv") as fh:
        for r in csv.DictReader(fh):
            if r["experiment"] != "main" or r["model"] not in MAIN_MODELS or r["run"] != "0":
                continue
            if r["config"] == "noguard" and r["unsafe"] == "1":
                score[r["task_id"]] += 1
            if r["config"] == "storageguard" and r["unsafe"] == "0":
                score[r["task_id"]] += 1 + float(r["success"])
            if r["config"] == "llm_judge" and r["unsafe"] == "1":
                score[r["task_id"]] += 0.5
    test = [t for t in engine.tasks().values() if t.split == "test"]
    picked = [HOOK_TASK]
    groups: dict[str, list] = defaultdict(list)
    for t in test:
        groups[t.trap_type or t.category].append(t)
    for key in sorted(groups):
        if key == "T1":  # the hook ticket already covers T1
            continue
        quota = 2 if key == "routine" else 1
        best = sorted(groups[key], key=lambda t: (-score[t.id], t.id))
        picked += [t.id for t in best if t.id not in picked][:quota]
    return picked


def export_runs(showcase: list[str]) -> dict[str, Any]:
    manifest: dict[str, Any] = {"showcase": showcase, "live": [], "recorded": [], "physical": [], "maps": []}
    for tid in showcase:
        write(f"map/{tid}.json", engine.task_map(tid))
        manifest["maps"].append(tid)
        for agent in ("naive", "reference"):
            for cfg in ("noguard", "prompt_only", "rbac", "storageguard"):
                write(f"live/{tid}__{agent}__{cfg}.json", engine.run_live(tid, f"scripted:{agent}", cfg))
                manifest["live"].append(f"{tid}__{agent}__{cfg}")
            write(f"live/{tid}__{agent}__storageguard__onehop.json",
                  engine.run_live(tid, f"scripted:{agent}", "storageguard", {"one_hop": True}))  # fmt: skip
            manifest["live"].append(f"{tid}__{agent}__storageguard__onehop")
        for cfg in ("noguard", "rbac", "storageguard"):
            write(f"physical/{tid}__naive__{cfg}.json", engine.run_live(tid, "scripted:naive", cfg, physical=True))
            manifest["physical"].append(f"{tid}__naive__{cfg}")
        for model in MAIN_MODELS:
            for cfg in MAIN_CONFIGS:
                try:
                    write(f"recorded/main__{model}__{cfg}__{tid}__r0.json", engine.replay_recorded("main", model, cfg, tid, 0))
                    manifest["recorded"].append(f"main__{model}__{cfg}__{tid}__r0")
                except KeyError:
                    pass
        print(f"  {tid} done", flush=True)
    return manifest


def export_sweeps(manifest: dict[str, Any]) -> None:
    keys = []
    for ta in TAU_ALLOW:
        for tb in TAU_BLOCK:
            if ta < tb:
                write(f"sweep/storageguard__{ta}__{tb}.json", engine.sweep("storageguard", {"tau_allow": ta, "tau_block": tb}))
                keys.append(f"storageguard__{ta}__{tb}")
    for cfg in ("noguard", "rbac"):
        write(f"sweep/{cfg}.json", engine.sweep(cfg, {}))
        keys.append(cfg)
    write("sweep/storageguard__onehop.json", engine.sweep("storageguard", {"one_hop": True}))
    keys.append("storageguard__onehop")
    manifest["sweep"] = keys
    manifest["tau_allow"], manifest["tau_block"] = TAU_ALLOW, TAU_BLOCK


def main() -> None:
    t0 = time.time()
    if "--results-only" in sys.argv:
        OUT.mkdir(parents=True, exist_ok=True)
        write("results.json", build_results())
        write("tasks.json", engine.all_task_summaries())
        print("results.json, tasks.json written")
        return
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    write("results.json", build_results())
    write("tasks.json", engine.all_task_summaries())
    print("results.json, tasks.json written")
    showcase = choose_showcase()
    print(f"showcase tickets ({len(showcase)}): {showcase}")
    manifest = export_runs(showcase)
    export_sweeps(manifest)
    import export_zfs  # the "On real storage" screen: recorded OpenZFS runs (results/zfs)

    export_zfs.main()
    manifest["generated_s"] = round(time.time() - t0, 1)
    write("manifest.json", manifest)
    size = sum(p.stat().st_size for p in OUT.rglob("*.json"))
    print(f"done in {time.time() - t0:.0f}s, {size / 1e6:.1f} MB in {OUT}")


if __name__ == "__main__":
    main()
